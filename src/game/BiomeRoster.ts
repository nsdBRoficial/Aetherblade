export interface BiomeUnitSpec {
  name: string;
  shortLabel: string;
  sheetKey: EnemySheetKey;
  colorGrade?: AtlasColorGrade;
  maxHp: number;
  damage: number;
  speedMult: number;
  scaleW: number;
  scaleH: number;
  hitWidth: number;
  hitHeight: number;
  accentHex: number;
  accentCss: string;
  projectileHex: number;
  projectileSpeed: number;
  projectileCount: number; // for rangers (e.g., 2 for Kitsune twin seals)
  bruteShockwave?: boolean; // heavy brute slams launch a ground shockwave
}

export interface BiomeBossProfile {
  name: string;
  title: string;
  sheetKey: EnemySheetKey;
  colorGrade?: AtlasColorGrade;
  maxHp: number;
  scaleW: number;
  scaleH: number;
  hitWidth: number;
  hitHeight: number;
  primaryHex: number;
  secondaryHex: number;
  accentCss: string;
  moveSpeed: number;
  dashSpeed: number;
  dashDamage: number;
  slamDamage: number;
  volleyDamage: number;
  volleyCountP1: number;
  volleyCountP2: number;
  volleySpeed: number;
  volleySpread: number;
  waveSpeed: number;
  volleyWeight: number;
  dashWeight: number;
  dashReleasesBladeWave?: boolean;
  slamSpawnsEmberRain?: boolean;
  volleyTripleBurst?: boolean;
}

export interface BiomeWaveEntry {
  type: Exclude<EnemyType, 'boss'>;
  x: number;
  y: number;
}

export interface BiomeRosterConfig {
  biome: BiomeId;
  units: Record<Exclude<EnemyType, 'boss'>, BiomeUnitSpec>;
  boss: BiomeBossProfile;
  waves: BiomeWaveEntry[];
}

